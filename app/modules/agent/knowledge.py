def is_data_question(question: str) -> bool:
    q = f" {stems(question)} "
    return any(f" {p} " in q or p in q for p in _DATA_INTENT_N)


_ORG_WORDS = tuple(stems(x) for x in ("هدف", "اهداف", "أهداف", "نتيجه", "نتائج", "مؤشر", "مستهدف", "قسم", "اقسام", "أقسام", "تقدم", "تقدّم", "متاخر", "متأخر", "خارج المسار", "على المسار",
                                       "بيانات", "مبيعات", "حالنا", "حالي"))


def mentions_org_data(question: str) -> bool:
    """Does the question talk about the person's own goals, results or data (so a computed briefing is a fair answer without a model)?"""
    q = f" {stems(question)} "
    return any(f" {w} " in q or w in q.split() for w in _ORG_WORDS) or is_data_question(question)


def match(question: str, is_on=lambda m: True) -> Entry | None:
    """The best guide entry for a question, or None. A phrase scores 2 per word (a longer phrase beats a short one), +3 when it is the whole question.
    A real question beats small talk: «مرحبا، كيف أنشئ هدفًا؟» is about creating a goal."""
    q = stems(question)
    if not q or is_data_question(question):
        return None
    padded = f" {q} "
    best = {False: (None, 0), True: (None, 0)}          # keyed by `small`
    for e in active(is_on):
        score = 0
        for k in e._k:
            if f" {k} " in padded:
                score = max(score, 2 * len(k.split()) + (3 if k == q else 0))
        if score > best[e.small][1]:
            best[e.small] = (e, score)
    real, small = best[False], best[True]
    if real[0] is not None and real[1] >= 2:
        return real[0]
    if small[0] is not None and len(q.split()) <= 5:
        return small[0]
    return None


def answer(question: str, is_on=lambda m: True, name: str = PRODUCT) -> dict | None:
    """-> {"answer": str, "suggestions": [..], "entry": id} from the guide, or None when the guide has nothing for this question."""
    e = match(question, is_on)
    if e is None:
        return None
    return {"answer": e.text.replace("{name}", name), "suggestions": [x.replace("{name}", name) for x in e.follow][:3], "entry": e.id}


