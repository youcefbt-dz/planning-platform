def brand_name() -> str:
    """The site's name from config/brand.yaml, so renaming the product renames the assistant too."""
    try:
        from flask import current_app, g

        return current_app.extensions["brand"].name_for(g.get("lang", "ar")) or PRODUCT
    except Exception:
        return PRODUCT


def active(is_on) -> list[Entry]:
    """Entries whose module is on. `is_on(module_id) -> bool`."""
    return [e for e in ENTRIES if not e.needs or is_on(e.needs)]


def guide_text(is_on=lambda m: True, modules_label: str = "", name: str = PRODUCT) -> str:
    """The product guide for the model's system prompt (everything it may say about the product, nothing else)."""
    lines = [f"PRODUCT GUIDE: everything you may say about {name}. If a product detail is not here, say you are not sure and point to where the person can look. Never invent features, buttons, prices or integrations.",
             f"- Name: {name}. Developer: {DEVELOPER}. Interface language: Arabic."]
    if modules_label:
        lines.append(f"- Parts of the product that are switched on in this workspace: {modules_label}.")
    for e in active(is_on):
        if e.small:
            continue
        lines.append(f"## {e.title}\n{e.text.replace('{name}', name)}")
    return "\n".join(lines)


