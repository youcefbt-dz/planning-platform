# -- normalisation -----------------------------------------------------------------------------------------------------------------------
_TASHKEEL = re.compile(r"[\u064B-\u065F\u0670\u0640]")
_PUNCT = re.compile(r"[^\w\s]")
_AR_DIGITS = str.maketrans("٠١٢٣٤٥٦٧٨٩", "0123456789")


def norm(text: str) -> str:
    """Lowercase, no diacritics, folded alef / teh-marbuta / alef-maqsura, no punctuation: so «مطوّر» matches «مطور» and «الأهداف» matches «الاهداف»."""
    s = _TASHKEEL.sub("", (text or "").casefold().translate(_AR_DIGITS))
    s = s.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا").replace("ة", "ه").replace("ى", "ي").replace("ؤ", "و").replace("ئ", "ي")
    return re.sub(r"\s+", " ", _PUNCT.sub(" ", s)).strip()


def _stem(tok: str) -> str:
    """Drop Arabic clitics so «المطور» matches «مطور» and «هدفًا» matches «هدف» (applied to both the keys and the question)."""
    for pre in ("وبال", "وال", "بال", "كال", "فال", "لل", "ال"):
        if tok.startswith(pre) and len(tok) - len(pre) >= 3:
            tok = tok[len(pre):]
            break
    if len(tok) > 3 and tok.endswith("ا"):
        tok = tok[:-1]
    return tok


def stems(text: str) -> str:
    return " ".join(_stem(t) for t in norm(text).split())


@dataclass(frozen=True)
class Entry:
    id: str
    title: str
    keys: tuple[str, ...]                 # phrases people use (normalised on load); a longer phrase that matches scores more
    text: str                             # the answer, in the product's own words
    follow: tuple[str, ...] = ()          # follow-up questions offered after the answer (written as the person would ask them)
    needs: str = ""                       # a module id that must be on for this entry to apply
    small: bool = False                   # small talk (greeting, thanks): answered offline only, never put in the model's guide
    _k: tuple[str, ...] = field(default=(), compare=False, repr=False)

    def __post_init__(self):
        object.__setattr__(self, "_k", tuple(dict.fromkeys(stems(k) for k in self.keys if stems(k))))


